/// Converts a theme category's word bank into [VocabEntry] rows so it can
/// flow through the same level-building pipeline as book/campaign words.
///
/// [categoryIndex] only needs to be stable *within one resolved category
/// list* (local fallback or a freshly-fetched remote list) — it seeds the
/// negative synthetic [VocabEntry.rowId] range so ids don't collide across
/// categories in the same session.
List<VocabEntry> wordBuilderThemeCategoryEntries(
  WordBuilderThemeCategory category,
  int categoryIndex,
) {
  final base = -(2000000 + categoryIndex * 1000);
  return [
    for (var i = 0; i < category.words.length; i++)
      VocabEntry(
        rowId: base - i,
        bookId: 'theme_${category.id}',
        word: category.words[i].word,
        type: '',
        meaningEn: '',
        meaningFa: category.words[i].fa,
        meaningKur: category.words[i].ckb,
        exampleEn: '',
        exampleFa: '',
        exampleKur: '',
        unit: 0,
        section: null,
      ),
  ];
}

int themeCategoryPlayableWordCount(
  WordBuilderThemeCategory category,
  int categoryIndex,
) {
  return wordBuilderThemeCategoryEntries(category, categoryIndex)
      .map(wordBuilderGameLemma)
      .where((w) => w != null && w.isNotEmpty)
      .length;
}

int themeCategoryStageCount(int playableWordCount) {
  if (playableWordCount <= 0) return 0;
  return (playableWordCount + kWordBuilderCampaignWordsPerStage - 1) ~/
      kWordBuilderCampaignWordsPerStage;
}

bool themeCategoryHasPlayableWords(
  WordBuilderThemeCategory category,
  int categoryIndex,
) {
  return themeCategoryPlayableWordCount(category, categoryIndex) > 0;
}

