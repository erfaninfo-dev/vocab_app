/// One themed vocabulary word with its Persian/Kurdish translations, used to
/// seed a [WordBuilderThemeCategory]'s word-builder session.
class WordBuilderThemeWord {
  const WordBuilderThemeWord(this.word, this.fa, this.ckb);

  final String word;
  final String fa;
  final String ckb;
}

/// A themed word bank (e.g. "Animals", "Food") the player can pick from the
/// Word Builder category screen instead of the IELTS/general "Normal" track.
class WordBuilderThemeCategory {
  const WordBuilderThemeCategory({
    required this.id,
    required this.nameEn,
    required this.nameFa,
    required this.nameCkb,
    required this.icon,
    required this.words,
  });

  final String id;
  final String nameEn;
  final String nameFa;
  final String nameCkb;
  final IconData icon;
  final List<WordBuilderThemeWord> words;

  String displayName(String languageCode) {
    switch (languageCode) {
      case 'fa':
        return nameFa;
      case 'ckb':
        return nameCkb;
      default:
        return nameEn;
    }
  }

  /// Builds a category from the server's `GET /game_word_categories.php`
  /// response. Falls back to a generic icon if [GameWordCategory.icon] isn't
  /// a name recognized by [_iconByName] (e.g. an older client vs. a newer
  /// server-side category).
  factory WordBuilderThemeCategory.fromRemote(GameWordCategory remote) {
    return WordBuilderThemeCategory(
      id: remote.slug,
      nameEn: remote.nameEn,
      nameFa: remote.nameFa,
      nameCkb: remote.nameCkb,
      icon: _iconByName(remote.icon),
      words: [
        for (final w in remote.words)
          WordBuilderThemeWord(w.word, w.meaningFa, w.meaningKur),
      ],
    );
  }
}

